"""The acquisition guide: the minimal instruction text a base model needs.

**It is part of the prompt envelope, so it must not encode one representation's
advantages.**  Four mechanical properties carry that claim, and each is a test in
``tests/releases/test_acquisition.py``:

1. :data:`PREAMBLE` and :data:`CLOSING` are frozen constants spliced around every guide.
   They are byte-identical for every surface -- the test compares them across the whole
   registry rather than trusting this sentence.
2. The surface-specific section is **generated by the surface from its own descriptor**
   (:meth:`surfaces.Surface.syntax_note`).  No hand-written per-candidate prompt exists to
   be tuned, which is precisely the failure mode ``docs/ROUTE_B_PARITY_AUDIT.md`` section 1
   found in the five historical arms.
3. No guide contains a candidate identifier, a surface identifier, or any word from
   :data:`BANNED_TERMS` (comparative, evaluative or release-status vocabulary).
4. Every surface's syntax note fits :data:`SYNTAX_BUDGET_CHARS`, so no arm can be helped by
   simply being explained at greater length.

**The honest limitation.**  Byte-identical shared text guarantees equal *content*, not
equal *helpfulness*.  A grammar a base model has seen more of in pretraining is easier to
acquire from the same number of words, and no static property of this file can correct for
that.  Only a matched experiment can measure it, and this package does not claim to have
run one.
"""

from __future__ import annotations

from arena.canonical.schema import stable_hash

from .surfaces import Surface

#: Comparative, evaluative and release-status vocabulary that may never reach the prompt.
BANNED_TERMS: tuple[str, ...] = (
    "advantage",
    "best",
    "better",
    "clearer",
    "easier",
    "efficient",
    "faster",
    "ideal",
    "natural choice",
    "optimal",
    "preferred",
    "recommend",
    "r*",
    "rstar",
    "should prefer",
    "simpler",
    "superior",
    "winner",
    "winning",
    "worse",
)

#: The syntax section's character budget.  Equal budgets keep explanation length from
#: acting as a hidden per-arm advantage.
SYNTAX_BUDGET_CHARS = 700

PREAMBLE = """\
You are reading a machine-facing description of a mathematical proof state.

A state contains:
- scopes: a forest of contexts. Every other record names the scope it lives in.
- declarations: named things -- objects, variables, binders, definitions, let-values and
  metavariables -- each with a type and a scope. A let-value carries its definition.
- claims: propositions with a role (assumption, fact, proposition, definition, identity),
  a scope, an epistemic status, and when verified a link to a verification record.
- goals: zero, one or many. Each names its own scope, so two goals may hold different
  contexts. At most one is marked as focused.
- obligations: proof debts, each in its own scope.
- evidence: verification records, each naming a verifier and its version.
- substitution: assignments to declared metavariables.
- actions: proposed reasoning steps.
- extensions: data the core does not model, carried verbatim rather than dropped.

An epistemic status is one of ASSUMED, PROPOSED, DERIVED, VERIFIED, REFUTED, OPEN.
VERIFIED is not yours to assert: it requires a named verifier and a verification record.
State DERIVED or PROPOSED and leave the verdict to the verifier.

An action names an operation, its targets, its arguments, an optional warrant, its
preconditions and the obligations it generates. Applying an action yields the next state;
a verifier, not you, decides whether the step was valid.

Type heads, operator symbols and operation names come from the libraries the state
declares. A symbol you do not recognise is data, not an error."""

CLOSING = """\
Unless you are told otherwise: read the state, then emit exactly one action, written in
the same notation as the state you were given. Emit nothing before or after it."""

_SYNTAX_HEADER = "SYNTAX"


def acquisition_guide(surface: Surface) -> str:
    """Assemble the guide for one surface: frozen text, generated syntax, frozen text."""

    note = surface.syntax_note().strip()
    if len(note) > SYNTAX_BUDGET_CHARS:
        raise ValueError(
            f"{surface.surface_id} syntax note is {len(note)} chars, over the "
            f"{SYNTAX_BUDGET_CHARS}-char neutrality budget"
        )
    return f"{PREAMBLE}\n\n{_SYNTAX_HEADER}\n{note}\n\n{CLOSING}\n"


def shared_sections(guide: str) -> tuple[str, str]:
    """Split a guide into the two sections that must be identical across surfaces."""

    head, _, rest = guide.partition(f"\n\n{_SYNTAX_HEADER}\n")
    if not rest:
        raise ValueError("guide is missing its syntax section")
    _, _, tail = rest.partition("\n\n")
    return head, tail


def guide_hash(surface: Surface) -> str:
    return stable_hash(
        {"surface": surface.descriptor().to_dict(), "guide": acquisition_guide(surface)}
    )


__all__ = [
    "BANNED_TERMS",
    "CLOSING",
    "PREAMBLE",
    "SYNTAX_BUDGET_CHARS",
    "acquisition_guide",
    "guide_hash",
    "shared_sections",
]
